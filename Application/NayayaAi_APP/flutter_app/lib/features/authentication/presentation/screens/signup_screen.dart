/// Registration.
///
/// Mirrors `POST /signup` exactly, including the rule that makes this screen
/// more than a four-field form: police, lawyer and judge must supply their own
/// unique ID, correctly prefixed (`POL`, `LAW`, `JUD`) and not already taken,
/// while a citizen's ID is generated by the server. So picking a role changes
/// what the form asks for, and the ID field appears and disappears with it.
///
/// AFTER SUCCESS the user is NOT signed in. The server registers the account and
/// returns without establishing a session -- it never sets a cookie on this
/// route. Rather than paper over that with a silent second request, the screen
/// shows the assigned unique ID (which a citizen has no other way to learn) and
/// sends the user to sign in with it acknowledged.
class SignupScreen extends ConsumerStatefulWidget {
  const SignupScreen({super.key});

  @override
  ConsumerState<SignupScreen> createState() => _SignupScreenState();
}

class _SignupScreenState extends ConsumerState<SignupScreen> {
  final _formKey = GlobalKey<FormState>();
  final _nameController = TextEditingController();
  final _emailController = TextEditingController();
  final _passwordController = TextEditingController();
  final _confirmController = TextEditingController();
  final _uniqueIdController = TextEditingController();

  final _nameFocus = FocusNode();
  final _emailFocus = FocusNode();
  final _passwordFocus = FocusNode();
  final _confirmFocus = FocusNode();
  final _uniqueIdFocus = FocusNode();

  UserRole _role = UserRole.citizen;
  String? _errorMessage;

  @override
  void dispose() {
    _nameController.dispose();
    _emailController.dispose();
    _passwordController.dispose();
    _confirmController.dispose();
    _uniqueIdController.dispose();
    _nameFocus.dispose();
    _emailFocus.dispose();
    _passwordFocus.dispose();
    _confirmFocus.dispose();
    _uniqueIdFocus.dispose();
    super.dispose();
  }

  void _handleRoleChanged(UserRole role) {
    if (role == _role) return;
    setState(() {
      _role = role;
      // A POL id left in the box after switching to Lawyer would fail server
      // validation with a message about a prefix the user can no longer see.
      if (!role.requiresUserSuppliedId) _uniqueIdController.clear();
      _errorMessage = null;
    });
  }

  Future<void> _handleSubmit() async {
    FocusScope.of(context).unfocus();
    setState(() => _errorMessage = null);

    if (!(_formKey.currentState?.validate() ?? false)) return;

    final controller = ref.read(authControllerProvider.notifier);

    try {
      final result = await controller.signup(
        fullName: _nameController.text,
        email: _emailController.text,
        password: _passwordController.text,
        role: _role,
        uniqueId: _uniqueIdController.text,
      );
      if (!mounted) return;
      await _showSuccess(result);
    } on Failure catch (failure) {
      if (!mounted) return;
      controller.clearFailure();
      setState(() => _errorMessage = failure.message);
    }
  }

  /// Confirms registration and hands off to sign-in.
  ///
  /// The unique ID is the reason this is a dialog and not a snackbar: for a
  /// citizen it is server-generated and shown here for the first and only time,
  /// so it must not be dismissible by a timeout while the user is reading it.
  ///
  /// When the email was already registered the server answers 200 with no ID
  /// and "If eligible, your account has been created." — so this shows that
  /// sentence and nothing else, rather than announcing an account that was not
  /// made. (The website prints "Your Unique ID: undefined" there.)
  Future<void> _showSuccess(SignupResult result) async {
    final scheme = Theme.of(context).colorScheme;
    final assignedId = result.uniqueId;

    await showDialog<void>(
      context: context,
      barrierDismissible: false,
      builder: (dialogContext) => AlertDialog(
        icon: Icon(
          Icons.check_circle_outline_rounded,
          color: scheme.primary,
          size: 40,
        ),
        title: result.hasUniqueId ? const Text('Account created') : null,
        content: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            Text(
              result.hasUniqueId
                  ? 'Your ${_role.label.toLowerCase()} account is registered. '
                      'Sign in with your email and password.'
                  : (result.message?.trim().isNotEmpty ?? false)
                      ? result.message!.trim()
                      : 'Sign in with your email and password.',
              textAlign: TextAlign.center,
              style: Theme.of(dialogContext).textTheme.bodyMedium,
            ),
            if (assignedId.isNotEmpty) ...[
              const SizedBox(height: AppSpacing.xl),
              Text(
                'YOUR UNIQUE ID',
                style: AppTypography.label.copyWith(
                  color: scheme.onSurface.withValues(alpha: 0.6),
                  letterSpacing: 1.1,
                ),
              ),
              const SizedBox(height: AppSpacing.xs),
              SelectableText(
                assignedId,
                style: AppTypography.fieldValue.copyWith(
                  fontSize: 22,
                  fontWeight: FontWeight.w700,
                  color: Theme.of(dialogContext).brightness == Brightness.dark
                      ? AppColors.saffronDark
                      : AppColors.saffron,
                ),
              ),
              const SizedBox(height: AppSpacing.xs),
              Text(
                'Keep this for your records.',
                textAlign: TextAlign.center,
                style: Theme.of(dialogContext).textTheme.bodySmall?.copyWith(
                      color: scheme.onSurface.withValues(alpha: 0.6),
                    ),
              ),
            ],
          ],
        ),
        actions: [
          FilledButton(
            onPressed: () => Navigator.of(dialogContext).pop(),
            child: const Text('Continue to sign in'),
          ),
        ],
      ),
    );

    if (!mounted) return;

    // Carry the email over so the user does not retype what they just entered.
    // `pop` rather than a fresh push: this screen was pushed from sign-in, so
    // popping returns to the instance already on the stack.
    final email = _emailController.text.trim();
    if (context.canPop()) {
      context.pop(email);
    } else {
      context.goNamed(AppRoutes.loginName);
    }
  }

  @override
  Widget build(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;
    final isDark = Theme.of(context).brightness == Brightness.dark;
    final keyboardOpen = MediaQuery.viewInsetsOf(context).bottom > 0;
    final busy = ref.watch(
      authControllerProvider.select(
        (s) => s.status == AuthStatus.authenticating,
      ),
    );

    return AnnotatedRegion<SystemUiOverlayStyle>(
      value: SystemUiOverlayStyle(
        statusBarColor: Colors.transparent,
        statusBarIconBrightness: Brightness.light,
        statusBarBrightness: Brightness.dark,
        systemNavigationBarColor: scheme.surface,
        systemNavigationBarIconBrightness:
            isDark ? Brightness.light : Brightness.dark,
      ),
      child: Scaffold(
        backgroundColor: AuthHeader.backgroundFor(context),
        body: Column(
          children: [
            SafeArea(
              bottom: false,
              child: Stack(
                children: [
                  AuthHeader(
                    title: 'Create account',
                    subtitle: 'Register for access to NyayaAI services.',
                    compact: keyboardOpen,
                  ),
                  Positioned(
                    top: AppSpacing.sm,
                    left: AppSpacing.sm,
                    child: IconButton(
                      onPressed: busy ? null : () => _handleBack(context),
                      icon: const Icon(Icons.arrow_back),
                      color: Colors.white,
                      tooltip: 'Back to sign in',
                    ),
                  ),
                ],
              ),
            ),
            Expanded(child: _buildSheet(context, scheme, busy)),
          ],
        ),
      ),
    );
  }

  void _handleBack(BuildContext context) {
    if (context.canPop()) {
      context.pop();
    } else {
      context.goNamed(AppRoutes.loginName);
    }
  }

  Widget _buildSheet(BuildContext context, ColorScheme scheme, bool busy) {
    return Container(
      width: double.infinity,
      decoration: BoxDecoration(
        color: scheme.surface,
        borderRadius: AppRadius.sheetTop,
      ),
      clipBehavior: Clip.antiAlias,
      child: SafeArea(
        top: false,
        child: SingleChildScrollView(
          physics: const AlwaysScrollableScrollPhysics(),
          padding: const EdgeInsets.fromLTRB(
            AppSpacing.xxl,
            AppSpacing.xxl,
            AppSpacing.xxl,
            AppSpacing.xxl,
          ),
          child: Center(
            child: ConstrainedBox(
              constraints: const BoxConstraints(
                maxWidth: AppSizes.maxFormWidth,
              ),
              child: _buildForm(context, busy),
            ),
          ),
        ),
      ),
    );
  }

  Widget _buildForm(BuildContext context, bool busy) {
    final saffron = Theme.of(context).brightness == Brightness.dark
        ? AppColors.saffronDark
        : AppColors.saffron;

    return Form(
      key: _formKey,
      child: AutofillGroup(
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            if (_errorMessage != null) ...[
              FormBanner(message: _errorMessage!),
              const SizedBox(height: AppSpacing.lg),
            ],
            RoleSelector(
              value: _role,
              onChanged: _handleRoleChanged,
              enabled: !busy,
            ),
            const SizedBox(height: AppSpacing.lg),
            AppTextField(
              label: 'Full name',
              controller: _nameController,
              focusNode: _nameFocus,
              validator: Validators.fullName,
              enabled: !busy,
              keyboardType: TextInputType.name,
              textCapitalization: TextCapitalization.words,
              textInputAction: TextInputAction.next,
              autofillHints: const [AutofillHints.name],
              inputFormatters: [LengthLimitingTextInputFormatter(80)],
              onSubmitted: (_) => _emailFocus.requestFocus(),
            ),
            const SizedBox(height: AppSpacing.sm),
            AppTextField(
              label: 'Email address',
              controller: _emailController,
              focusNode: _emailFocus,
              validator: Validators.email,
              enabled: !busy,
              hintText: 'you@example.com',
              keyboardType: TextInputType.emailAddress,
              textInputAction: TextInputAction.next,
              autofillHints: const [AutofillHints.email],
              inputFormatters: [
                TextInputFormatter.withFunction(
                  (_, next) => next.copyWith(text: next.text.toLowerCase()),
                ),
                FilteringTextInputFormatter.deny(RegExp(r'\s')),
              ],
              onSubmitted: (_) => _passwordFocus.requestFocus(),
            ),
            const SizedBox(height: AppSpacing.sm),
            PasswordField(
              controller: _passwordController,
              label: 'Choose a password',
              validator: Validators.signupPassword,
              enabled: !busy,
              focusNode: _passwordFocus,
              autofillHints: const [AutofillHints.newPassword],
              textInputAction: TextInputAction.next,
              onSubmitted: (_) => _confirmFocus.requestFocus(),
            ),
            // The website's strength meter (signup.html:417-422, 480-491).
            // Advisory: the server's rule is the one that decides.
            Padding(
              padding: const EdgeInsets.only(top: AppSpacing.xs),
              child: ValueListenableBuilder<TextEditingValue>(
                valueListenable: _passwordController,
                builder: (context, value, _) =>
                    PasswordStrengthMeter(password: value.text),
              ),
            ),
            const SizedBox(height: AppSpacing.sm),
            // The website's "Confirm" box and its "Passwords do not match"
            // (signup.html:428-431, 501-504).
            PasswordField(
              controller: _confirmController,
              label: 'Confirm password',
              validator: (v) =>
                  Validators.confirmPassword(v, _passwordController.text),
              enabled: !busy,
              focusNode: _confirmFocus,
              autofillHints: const [AutofillHints.newPassword],
              textInputAction: _role.requiresUserSuppliedId
                  ? TextInputAction.next
                  : TextInputAction.done,
              onSubmitted: (_) => _role.requiresUserSuppliedId
                  ? _uniqueIdFocus.requestFocus()
                  : _handleSubmit(),
            ),
            // Professional roles only. The server generates a citizen's ID and
            // ignores anything sent for one, so asking would be a field whose
            // value is discarded.
            if (_role.requiresUserSuppliedId) ...[
              const SizedBox(height: AppSpacing.sm),
              AppTextField(
                label: '${_role.label} ID',
                controller: _uniqueIdController,
                focusNode: _uniqueIdFocus,
                validator: (v) => Validators.uniqueId(v, _role),
                enabled: !busy,
                hintText: '${_role.idPrefix}001',
                keyboardType: TextInputType.visiblePassword,
                textCapitalization: TextCapitalization.characters,
                textInputAction: TextInputAction.done,
                // Saffron marks operator-supplied identity, matching the footer.
                valueStyle: AppTypography.fieldValue.copyWith(color: saffron),
                inputFormatters: [
                  // The server uppercases before comparing, so uppercasing as
                  // they type keeps what is on screen identical to what is
                  // checked -- no silent transformation between the two.
                  TextInputFormatter.withFunction(
                    (_, next) => next.copyWith(text: next.text.toUpperCase()),
                  ),
                  FilteringTextInputFormatter.allow(RegExp(r'[A-Z0-9\-/]')),
                  LengthLimitingTextInputFormatter(20),
                ],
                onSubmitted: (_) => _handleSubmit(),
              ),
              _buildIdHint(context),
            ],
            const SizedBox(height: AppSpacing.lg),
            PrimaryButton(
              label: 'Create account',
              icon: Icons.person_add_alt_1_outlined,
              isLoading: busy,
              onPressed: _handleSubmit,
            ),
            const SizedBox(height: AppSpacing.xl),
            _buildSignInPrompt(context, busy),
          ],
        ),
      ),
    );
  }

  Widget _buildIdHint(BuildContext context) {
    final scheme = Theme.of(context).colorScheme;

    return Padding(
      padding: const EdgeInsets.only(top: AppSpacing.xs),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Icon(
            Icons.info_outline_rounded,
            size: 15,
            color: scheme.onSurface.withValues(alpha: 0.55),
          ),
          const SizedBox(width: AppSpacing.sm),
          Expanded(
            child: Text(
              'Must start with ${_role.idPrefix} and match the ID issued to you.',
              style: Theme.of(context).textTheme.bodySmall?.copyWith(
                    color: scheme.onSurface.withValues(alpha: 0.55),
                    height: 1.3,
                  ),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildSignInPrompt(BuildContext context, bool busy) {
    final theme = Theme.of(context);

    // Wrap for the same reason as the sign-in screen's prompt: prompt plus
    // action can exceed the form column, and wrapping beats clipping.
    return Wrap(
      alignment: WrapAlignment.center,
      crossAxisAlignment: WrapCrossAlignment.center,
      children: [
        Text(
          'Already registered?',
          style: theme.textTheme.bodyMedium?.copyWith(
            color: theme.colorScheme.onSurface.withValues(alpha: 0.7),
          ),
        ),
        TextButton(
          onPressed: busy ? null : () => _handleBack(context),
          child: const Text('Sign in'),
        ),
      ],
    );
  }
}
